// Command bare generates an intermediate CSAF model from both versioned models.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strconv"
)

func typeName(node *match) string {
	if node.raw {
		return "json.RawMessage"
	}
	switch node.shape {
	case "pointer":
		return "*" + typeName(node.elem)
	case "slice":
		return "[]" + typeName(node.elem)
	case "struct":
		return node.name
	default:
		return node.shape
	}
}

func generate(rootName, v20Dir, v21Dir string) ([]byte, error) {
	left, err := loadModel(v20Dir)
	if err != nil {
		return nil, err
	}
	right, err := loadModel(v21Dir)
	if err != nil {
		return nil, err
	}
	structures, err := compareModels(left, right, rootName)
	if err != nil {
		return nil, err
	}
	var source bytes.Buffer
	source.WriteString("// SPDX-License-Identifier: Apache-2.0\n")
	source.WriteString("// SPDX-FileCopyrightText: 2026 German Federal Office for Information Security (BSI) <https://www.bsi.bund.de>\n")
	source.WriteString("// Software-Engineering: 2026 Intevation GmbH <https://intevation.de>\n\n")
	source.WriteString("// Code generated by internal/generate/bare.\n\npackage bare\n\n")
	var declarations bytes.Buffer
	usesRaw := false
	for _, structure := range structures {
		fmt.Fprintf(&declarations, "type %s struct {\n", structure.name)
		for _, field := range structure.fields {
			typ := typeName(field.typ)
			if typ == "json.RawMessage" {
				usesRaw = true
			}
			tag := field.jsonName
			if field.omitEmpty {
				tag += ",omitempty"
			}
			fmt.Fprintf(&declarations, "%s %s `json:%s`\n", field.goName, typ, strconv.Quote(tag))
		}
		declarations.WriteString("}\n\n")
	}
	if usesRaw {
		source.WriteString("import \"encoding/json\"\n\n")
	}
	source.Write(declarations.Bytes())
	return format.Source(source.Bytes())
}

var roots = map[string]string{
	"CSAF":       "internal/bare/csaf_generated.go",
	"Aggregator": "internal/bare/aggregator_generated.go",
	"Provider":   "internal/bare/provider_generated.go",
}

func main() {
	for rootName, output := range roots {
		source, err := generate(rootName, "csaf/v20", "csaf/v21")
		if err != nil {
			log.Fatal(err)
		}
		if err := os.WriteFile(output, source, 0o644); err != nil {
			log.Fatal(err)
		}
	}
}
