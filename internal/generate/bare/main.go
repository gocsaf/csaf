// bare generates intermediate models and typed common models
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

func typeName(node *match) string {
	if node.raw {
		return "json.RawMessage"
	}
	switch node.shape {
	case "pointer":
		return "*" + typeName(node.elem)
	case "slice":
		return "[]" + typeName(node.elem)
	case "struct":
		return node.name
	default:
		return node.shape
	}
}

func generateBare(structures []*match) ([]byte, error) {
	var source bytes.Buffer
	source.WriteString("// SPDX-License-Identifier: Apache-2.0\n")
	source.WriteString("// SPDX-FileCopyrightText: 2026 German Federal Office for Information Security (BSI) <https://www.bsi.bund.de>\n")
	source.WriteString("// Software-Engineering: 2026 Intevation GmbH <https://intevation.de>\n\n")
	source.WriteString("// Code generated by internal/generate/bare.\n\npackage bare\n\n")
	var declarations bytes.Buffer
	usesRaw := false
	usesDateTime := false
	for _, structure := range structures {
		fmt.Fprintf(&declarations, "type %s struct {\n", structure.name)
		for _, field := range structure.fields {
			typ := typeName(field.typ)
			if typ == "json.RawMessage" {
				usesRaw = true
			}
			if strings.Contains(typ, "v21.DateTime") {
				usesDateTime = true
			}
			tag := field.jsonName
			if field.omitEmpty {
				tag += ",omitempty"
			}
			fmt.Fprintf(&declarations, "%s %s `json:%s`\n", field.goName, typ, strconv.Quote(tag))
		}
		declarations.WriteString("}\n\n")
	}
	if usesRaw || usesDateTime {
		source.WriteString("import (\n")
		if usesRaw {
			source.WriteString("\"encoding/json\"\n")
		}
		if usesDateTime {
			source.WriteString("\n\"github.com/gocsaf/csaf/v3/csaf/v21\"\n")
		}
		source.WriteString(")\n\n")
	}
	source.Write(declarations.Bytes())
	return format.Source(source.Bytes())
}

var roots = map[string]struct {
	barePath    string
	packageName string
}{
	"CSAF":       {"internal/bare/csaf_generated.go", "advisory"},
	"Aggregator": {"internal/bare/aggregator_generated.go", "aggregator"},
	"Provider":   {"internal/bare/provider_generated.go", "provider"},
}

func main() {
	left, err := loadModel("csaf/v20")
	if err != nil {
		log.Fatal(err)
	}
	right, err := loadModel("csaf/v21")
	if err != nil {
		log.Fatal(err)
	}
	outputs := make(map[string][]byte)
	for _, rootName := range slices.Sorted(maps.Keys(roots)) {
		root := roots[rootName]
		structures, err := compareModels(left, right, rootName)
		if err != nil {
			log.Fatal(err)
		}
		source, err := generateBare(structures)
		if err != nil {
			log.Fatal(err)
		}
		outputs[root.barePath] = source
		model, err := newTypedModel(left, right, rootName, structures[0])
		if err != nil {
			log.Fatal(err)
		}
		outputs[filepath.Join("csaf", root.packageName, "model_generated.go")], err = model.emitModel(root.packageName)
		if err != nil {
			log.Fatal(err)
		}
		outputs[filepath.Join("csaf", root.packageName, "from_bare_generated.go")], err = model.emitConverter(root.packageName)
		if err != nil {
			log.Fatal(err)
		}
		outputs[filepath.Join("csaf", root.packageName, "check_generated.go")], err = model.emitCheck(root.packageName)
		if err != nil {
			log.Fatal(err)
		}
	}

	for _, output := range slices.Sorted(maps.Keys(outputs)) {
		if err := os.MkdirAll(filepath.Dir(output), 0755); err != nil {
			log.Fatal(err)
		}
		if err := os.WriteFile(output, outputs[output], 0644); err != nil {
			log.Fatal(err)
		}
	}
}
